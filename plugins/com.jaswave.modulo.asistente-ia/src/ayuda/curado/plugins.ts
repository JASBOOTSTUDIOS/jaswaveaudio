import type { ControlAyuda, FichaAyuda } from '@jaswave/host-sdk'

/**
 * Fichas CURADAS de los plugins de JasWave, escritas para quien nunca ha usado un DAW.
 * Nombres, rangos y valores salen de `jaswave-plugin.json` de cada plugin (o del código fuente en el caso del Sampler).
 * Las «recetas» son puntos de partida orientativos: se ajustan de oído.
 */

type Tipo = 'instrumento' | 'efecto'

type Def = {
  slug: string
  titulo: string
  tipo: Tipo
  nivel?: 'principiante' | 'intermedio' | 'experto'
  /** Qué es y para qué sirve, en palabras simples. */
  que: string
  controles: ControlAyuda[]
  /** Recetas: «Resultado: cómo conseguirlo». */
  recetas: string[]
  relacionadas?: string[]
  etiquetas?: string[]
  /** Nota extra de uso (p. ej. MIDI). */
  nota?: string
}

const c = (slug: string, id: string, etiqueta: string, descripcion: string): ControlAyuda => ({ ayuda: `plugin.${slug}.${id}`, etiqueta, descripcion })

const pasosCarga = (d: Def): string[] =>
  d.tipo === 'instrumento'
    ? [
        'Selecciona una pista MIDI (o crea una con «Nueva pista MIDI»). Un instrumento necesita notas MIDI para sonar.',
        `Abre el panel Instrumentos, busca «${d.titulo}» e insértalo en la pista seleccionada. También puedes pedírselo a Jas: «pon ${d.titulo} en esta pista».`,
        'Arma la pista y toca tu teclado MIDI, o dibuja notas en el Piano roll, para oírlo.',
        'Ajusta sus controles en el Editor de plugin (panel derecho).',
      ]
    : [
        'Selecciona la pista (o el Master) a la que quieres aplicar el efecto.',
        `Abre el panel FX Chain y añade «${d.titulo}» a la cadena de esa pista. También puedes pedírselo a Jas.`,
        'Ajusta sus controles en el Editor de plugin (panel derecho).',
        'Usa Bypass para comparar el sonido con y sin efecto: si no oyes mejora, déjalo apagado.',
      ]

const plugin = (d: Def): FichaAyuda => ({
  id: `plugin:${d.slug}`,
  tipo: 'plugin',
  titulo: `JasWave ${d.titulo}`,
  resumen: `${d.que} Es un ${d.tipo === 'instrumento' ? 'instrumento (produce el sonido a partir de notas MIDI)' : 'efecto (transforma un sonido que ya existe)'}.${d.nota ? ' ' + d.nota : ''}`,
  nivel: d.nivel ?? 'principiante',
  comoAbrir: { herramienta: d.tipo === 'instrumento' ? 'instruments' : 'fx-chain' },
  pasos: [...pasosCarga(d), ...d.recetas.map((r) => `Receta · ${r}`)],
  controles: d.controles,
  relacionadas: [
    ...(d.tipo === 'instrumento' ? ['panel:instruments', 'panel:piano-roll'] : ['panel:fx-chain']),
    'panel:plugin-editor',
    ...(d.relacionadas ?? []),
  ],
  etiquetas: d.etiquetas,
  fuente: 'curada',
})

const BYP = (s: string) => c(s, 'bypass', 'Bypass', 'Apaga el plugin sin quitarlo, para comparar con y sin él.')
const VOL = (s: string, id = 'volume', nombre = 'Volumen principal') => c(s, id, nombre, 'Nivel de salida. Rango -24 a +6 dB (0 = sin cambio).')

