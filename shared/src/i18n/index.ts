export type SupportedLanguage = 'es' | 'en';

export const catalogs: Record<SupportedLanguage, TranslationCatalog> = {
  es,
  en,
};

export function useTranslation(language: SupportedLanguage = 'es') {
  const catalog = catalogs[language] ?? catalogs.es;

  const t = (key: string, fallback?: string): string => {
    return catalog[key] ?? fallback ?? key;
  };

  return { t, language, catalog };
}
